(defn make-lowerer
  "Build a scalar-expression lowerer.

   Returns source lowering entries `:lower` and `:lower-region`, plus typed builder entries
   `:cast`, `:load` and `:compute`. `:lower` accepts expression, expected dtype, and a map of typed
   local values. `:lower-region` accepts an ordered {:bindings [...] :results [...]} region, result dtypes,
   retained binding dtypes, and typed locals; it returns shared SSA operations and ordered results.
   Neither entry point stores tuple results: the schedule must commit all components together.
   `decline!` is called as `(decline! rule message data)` so each owning schedule retains an honest,
   local coverage contract. `:cast` converts an already-lowered value to a target dtype, with source
   context as its third argument. Owners may supply `conversion-policy` (source/target dtypes)
   and `load-other` (storage dtype); these do not change source-language admission.
   `require-source-types?` requires retained compound source dtypes at conversion boundaries
   and preserves retained integral arithmetic before floating consumer conversion. Older
   packed owners retain their explicit widened-integer policy until separately migrated.
   `scalar-ranges` may carry owner-proved intervals for declared integral scalar inputs. This
   builder validates their shape and representability but the owner remains responsible for the
   semantic proof establishing a tighter interval than the declared dtype.
   Fragment callers may supply their complete `source-region` up front. Together with the declared
   scalar/array/index scope this reserves source identities once; subsequent environments must
   contain only those identities or values generated by this builder.
   `:load` accepts a declared buffer and proved coordinate vector; `:compute` accepts a canonical
   operator, result dtype, already-converted argument vector and explicit operation options.
   `:fresh-binding` reserves an SSA identity for an owner's structured-control binder.
   `:owner-load-coordinates` optionally supplies independently proved coordinate vectors for
   closed layout regions; when supplied, retained source indices are not a second authority.
   `:scalar-math` is a closed, default-empty operation/dtype realization policy. It is validated
   once here and retained in scalar expressions; it does not infer hardware capability.
   These typed entries leave admission and proofs to the owner and final KernelBody validation."
  [{:keys [array-types scalar-types scalar-ranges arrays index-scope lower-index lower-load-index predicate id-prefix decline!
           conversion-policy load-other source-region require-source-types? owner-load-coordinates scalar-math]
    :or {id-prefix "scalar" scalar-ranges {}}}]
  (let [scalar-math (numerics/validate-scalar-math-policy! scalar-math)
        canon-type #(if (= :predicate %) :predicate (dtype/canon %))
        normalized-form (fn [form type source]
                          (with-meta form (assoc (meta source) :raster.type/tag
                                                 (dtype/scalar-tag-for-dtype type))))
        counter (atom 0)
        ;; One product Fold may feed several component projections in the same scalar region.
        ;; Cache its multi-result SSA refinement so projections never duplicate the loop or its
        ;; loads. `lower-region` creates a fresh builder per owning kernel region.
        product-fold-cache (atom {})
        reserved (atom (set (concat arrays (keys array-types) (keys scalar-types) index-scope)))
        reserve! (fn [form]
                   (swap! reserved into (filter symbol? (tree-seq coll? seq form))))
        _ (reserve! [source-region predicate])
        fresh (fn [prefix]
                (loop []
                  (let [id (symbol (str id-prefix "-" prefix "-" (swap! counter inc)))]
                    (if (contains? @reserved id)
                      (recur)
                      (do (swap! reserved conj id) id)))))
        ;; A schedule may have an array-specific coordinate proof (for example, a resident
        ;; one-element reduction result broadcast into a later fold). Keep that storage fact in
        ;; the owning schedule rather than teaching this shared scalar language about layouts.
        lower-load-index (or lower-load-index
                             (fn [_array expression scope]
                               (lower-index expression scope)))
        validated-scalar-ranges
        (into {}
              (map (fn [[id range]]
                     (let [type (some-> (get scalar-types id) canon-type)]
                       (when-not (and (symbol? id) type
                                      (map? range) (integer? (:lower range))
                                      (integer? (:upper range))
                                      (<= (:lower range) (:upper range))
                                      (scalar-range/contained-in-dtype? range type))
                         (throw (ex-info "owner scalar range must fit its declared integral dtype"
                                         {:reason :invalid-scalar-range-proof
                                          :scalar id :range range :dtype type})))
                       [id (select-keys range [:lower :upper])]))
                   scalar-ranges))
        ;; Lowered SSA names retain their exact interval here.  The public local environment still
        ;; carries only authoritative dtypes; this private table is a proof cache, not a type or
        ;; function registry, and a missing entry simply declines certification.
        value-ranges (atom validated-scalar-ranges)
        remember-range! (fn [id range]
                          (when range (swap! value-ranges assoc id range))
                          range)
        known-range (fn [value type]
                      (or (get @value-ranges value) (scalar-range/for-dtype type)))
        retained-type (fn [expression]
                        (or (when (and (seq? expression)
                                       (descriptor/cast-op?
                                        (descriptor/semantic-op expression)))
                              (some-> (descriptor/semantic-op expression)
                                      descriptor/cast-result-tag
                                      dtype/dtype-for-scalar-tag))
                            (let [tag (or (:raster.type/tag (meta expression))
                                          (:tag (meta expression)))]
                              (or (when (and (keyword? tag) (dtype/known? tag))
                                    (dtype/canon tag))
                                  (dtype/dtype-for-scalar-tag tag)))))
        authoritative-source-type
        (fn authoritative-source-type [expression env]
          (or (retained-type expression)
              (cond
                (instance? raster.compiler.ir.kernel_body.Literal expression)
                (canon-type (:type expression))

                (number? expression)
                (some-> expression types/literal-tag dtype/dtype-for-scalar-tag)

                (boolean? expression) :predicate

                (symbol? expression)
                (or (some-> (or (get env expression) (get scalar-types expression)) canon-type)
                    ;; Java numeric fields are a closed literal set in numeric-constant, not
                    ;; arbitrary var/field resolution. Their runtime value supplies independent
                    ;; source-width evidence before an explicit conversion is lowered.
                    (some-> (numeric-constant/value expression) :value
                            types/literal-tag dtype/dtype-for-scalar-tag canon-type))

                (descriptor/aget-call? expression)
                (some-> (get array-types (descriptor/aget-array-sym expression)) canon-type)

                (and (seq? expression) (descriptor/cast-op? (first expression)))
                (some-> (descriptor/cast-result-tag (first expression))
                        dtype/dtype-for-scalar-tag)

                ;; Canonical Fold owns its scalar result dtype in the typed dialect. This is an
                ;; intrinsic region contract, not an inference from an enclosing consumer cast.
                (dialect/scalar-fold-form? expression)
                (some-> expression dialect/scalar-fold-parts :attributes :dtype canon-type)

                (dialect/product-component-form? expression)
                (let [[_ product ordinal] expression
                      dtypes (get-in (dialect/product-fold-parts product)
                                     [:attributes :dtypes])]
                  (when (< -1 ordinal (count dtypes))
                    (canon-type (nth dtypes ordinal))))

                (dialect/scalar-convert-form? expression)
                (some-> expression dialect/scalar-convert-parts
                        :attributes :target-dtype canon-type)

                (and (seq? expression) (= 1 (count (descriptor/call-args expression)))
                     (contains? '#{pos? neg? zero? clojure.core/pos? clojure.core/neg?
                                   clojure.core/zero? raster.numeric/pos? raster.numeric/neg?
                                   raster.numeric/zero?}
                                (descriptor/semantic-op expression)))
                :predicate

                ;; The canonical ordered-loop matcher supplies the only source loop shape this
                ;; lowerer accepts. Prove its carry from the initializer, then type the update in
                ;; the lexical accumulator/index scope and require an invariant dtype before the
                ;; exit can establish the loop result. No arbitrary loop inference is admitted.
                (and (seq? expression) (contains? #{'loop 'loop*} (first expression)))
                (when-let [{:keys [acc-sym acc-init index-sym update-expr else-expr]}
                           (match-ordered-loop expression)]
                  (when-let [initial-type (authoritative-source-type acc-init env)]
                    (let [loop-env (assoc env index-sym :long acc-sym (canon-type initial-type))
                          update-type (authoritative-source-type update-expr loop-env)]
                      (when (and update-type
                                 (= (canon-type initial-type) (canon-type update-type)))
                        (if (= else-expr acc-sym)
                          (canon-type initial-type)
                          (authoritative-source-type else-expr loop-env))))))

                ;; A lexical result is authoritative when every preceding binder obtains its
                ;; dtype from its own annotation or initializer and the final expression can be
                ;; typed in that extended environment. This is a type-only ordered walk: it must
                ;; not call `lower-let`, evaluate an initializer, or duplicate emitted effects.
                (and (seq? expression)
                     (contains? #{'let 'let* 'clojure.core/let} (first expression)))
                (let [[_ bindings & body-expressions] expression]
                  (when (and (vector? bindings) (even? (count bindings))
                             (= 1 (count body-expressions)))
                    (when-let [extended
                               (reduce
                                (fn [environment [id init]]
                                  (when environment
                                    (when-let [binding-type
                                               (or (retained-type id)
                                                   (authoritative-source-type init environment))]
                                      (assoc environment id (canon-type binding-type)))))
                                env (partition 2 bindings))]
                      (authoritative-source-type (first body-expressions) extended))))

                ;; The shared inference layer owns scalar promotion/result contracts. Invoke it
                ;; only after every operand has an independent type; its legacy partial-operand
                ;; fallback must never turn an unknown expression into evidence for a cast.
                (and (seq? expression)
                     (let [intrinsic (some-> expression descriptor/semantic-op
                                              intrinsics/canonical intrinsics/descriptor)]
                       (and intrinsic (not= :cmp (:kind intrinsic)))))
                (let [arguments (vec (descriptor/call-args expression))
                      argument-types (mapv #(authoritative-source-type % env) arguments)]
                  (when (and (seq arguments) (every? some? argument-types))
                    (let [source-operation (descriptor/semantic-op expression)
                          qualified-operation (when (and (symbol? source-operation)
                                                         (nil? (namespace source-operation)))
                                                (symbol "clojure.core"
                                                        (name source-operation)))
                          inference-operation
                          (if (and qualified-operation
                                   (not (contains? util/*shadowing-locals* source-operation))
                                   (descriptor/scalar-op? qualified-operation))
                            qualified-operation source-operation)
                          operator (intrinsics/canonical source-operation)
                          intrinsic (intrinsics/descriptor operator)
                          inferred
                          (cond
                            (and (= :- operator) (= 1 (count argument-types)))
                            (first argument-types)

                            (ordered-fold-intrinsic? intrinsic operator (count argument-types))
                            (reduce (fn [left right]
                                      (when left
                                        (inference/infer-scalar-intrinsic-dtype
                                         inference-operation [left right] *ns*)))
                                    argument-types)

                            :else
                            (inference/infer-scalar-intrinsic-dtype
                             inference-operation argument-types *ns*))]
                      (some-> inferred canon-type))))

                ;; A value conditional owns a result type when both alternatives independently
                ;; prove the same type. The enclosing cast target contributes no evidence.
                (and (seq? expression) (= 'if (first expression)) (= 4 (count expression)))
                (let [condition (second expression)
                      constant-condition?
                      (or (nil? condition) (boolean? condition) (keyword? condition)
                          (number? condition) (string? condition) (char? condition))]
                  (if constant-condition?
                    (authoritative-source-type
                     (if (or (nil? condition) (false? condition))
                       (nth expression 3) (nth expression 2)) env)
                    (let [then-type (authoritative-source-type (nth expression 2) env)
                          else-type (authoritative-source-type (nth expression 3) env)]
                      (when (and then-type else-type
                                 (= (canon-type then-type) (canon-type else-type)))
                        (canon-type then-type)))))

                (and (seq? expression)
                     (= :cmp (:kind (intrinsics/descriptor
                                     (intrinsics/canonical
                                      (descriptor/semantic-op expression))))))
                :predicate)))
        source-type
        (fn source-type [expression expected env]
          (or
           (retained-type expression)
           (when require-source-types?
             (authoritative-source-type expression env))
           (cond
               (and (seq? expression)
                    (contains? #{'let 'let* 'clojure.core/let} (first expression)))
               (decline! :scalar-source-type
                         "scalar let used at a conversion boundary requires a retained result dtype"
                         {:expression expression :consumer-dtype expected})

               (instance? raster.compiler.ir.kernel_body.Literal expression) (:type expression)
               (symbol? expression) (or (get env expression) (get scalar-types expression) expected)
               (number? expression) expected
               (descriptor/aget-call? expression)
               (or (get array-types (descriptor/aget-array-sym expression)) expected)
               (and (seq? expression) (descriptor/cast-op? (first expression)))
               (dtype/dtype-for-scalar-tag (descriptor/cast-result-tag (first expression)))
               (and (seq? expression)
                    (= :cmp (:kind (intrinsics/descriptor
                                    (intrinsics/canonical
                                     (descriptor/semantic-op expression))))))
               :predicate
               :else (if (and require-source-types? (seq? expression))
                       (decline! :scalar-source-type
                                 "scalar conversion requires the retained source expression dtype"
                                 {:expression expression :consumer-dtype expected
                                  :environment env :scalar-types scalar-types})
                       expected))))]
    (when-not (and (fn? lower-index) (fn? decline!))
      (throw (ex-info "scalar KernelBody lowering requires index and decline callbacks"
                      {:reason :raster/bug :lower-index lower-index :decline decline!})))
    (letfn [(with-fold-index-range [id lower-bound upper-bound upper-mode env emit]
              ;; Only the actual counted index receives a body-entry fact. Bounds are
              ;; already lowered, and every prefix is checked by the shared interval
              ;; authority against retained SSA/ABI types, not a source-name guess.
              (let [saved @value-ranges
                    types (into {} (keep (fn [[value type]]
                                           (let [type (canon-type type)]
                                             (when (contains? #{:int :long} type)
                                               [value type]))))
                                (merge scalar-types env))
                    ranges (into {} (map (fn [[value type]]
                                          [value (known-range value type)])) types)
                    lower-range (scalar-range/typed-index-range lower-bound types ranges)
                    upper-range (scalar-range/typed-index-range upper-bound types ranges)
                    entry (when (= :exclusive upper-mode)
                            (scalar-range/exclusive-positive-loop-entry-range
                             lower-range upper-range 1 :long))]
                (try
                  (when entry (swap! value-ranges assoc id entry))
                  (emit)
                  (finally (reset! value-ranges saved)))))

            (load-ssa [array coordinates]
              (let [type (some-> (get array-types array) dtype/canon)]
                (when-not (and (contains? arrays array) type)
                  (decline! :indexed-load "scalar loads require a declared typed stable tensor"
                            {:array array :array-types array-types}))
                (reserve! [array coordinates predicate])
                (let [id (fresh "load") range (scalar-range/for-dtype type)]
                  (remember-range! id range)
                  {:operations [(body/->ScalarLoad
                                 (body/value id type) array coordinates predicate
                                 (when predicate (if load-other (load-other type)
                                                     (body/literal 0 type))) :cached)]
                   :result id :type type :range range})))

            (compute-ssa [operator result-type arguments options range]
              (reserve! arguments)
              (let [result-type (canon-type result-type)
                    result (fresh "value")
                    range (or range (scalar-range/for-dtype result-type))
                    realization (numerics/scalar-math-realization
                                 scalar-math (intrinsics/canonical operator) result-type)
                    options (cond-> options realization (assoc :math-realization realization))]
                (remember-range! result range)
                {:operations [(body/->ScalarCompute
                               (body/value result result-type)
                               (body/scalar-expression operator result-type arguments options))]
                 :result result :type result-type :range range}))

            (total-source-cast-literal? [lowered source-op]
              ;; Consult the lowered operand, not a source spelling that could name
              ;; a lexical value instead of the apparent Java numeric field.
              (when (and (descriptor/cast-op? source-op)
                         (instance? raster.compiler.ir.kernel_body.Literal (:result lowered)))
                (some? (numeric-constant/source-value
                        (list (symbol "clojure.core" (name source-op))
                              (:value (:result lowered)))))))

            (cast-lowered [lowered target expression & [explicit-source-op]]
              (let [target (dtype/canon target)]
                (if (= target (:type lowered))
                  lowered
                  (let [source (dtype/canon (:type lowered))
                        ;; A proved integral interval makes narrowing total regardless of whether
                        ;; the source wrote an explicit cast.  This is what permits ordinary
                        ;; predicates such as `(> int-value 0)`: the Clojure literal is a Long,
                        ;; but its singleton range is exactly representable as an int.  Unknown or
                        ;; wider ranges still require the owner's explicit conversion policy.
                        proved-exact-narrowing?
                        (and (not (dtype/fp-dtype? source))
                             (not (dtype/fp-dtype? target))
                             (scalar-range/contained-in-dtype? (:range lowered) target))
                        [rounding overflow]
                        (if proved-exact-narrowing?
                          [:exact :exact]
                          ;; An explicit source cast owns its checked-versus-unchecked narrowing
                          ;; contract. Implicit conversions continue to use the owner's policy, or
                          ;; the legacy map/fold wrap default when the owner supplies none.
                          (or (if explicit-source-op
                                (scalar-conversion/source-policy source target explicit-source-op)
                                (if conversion-policy
                                  (conversion-policy source target)
                                  ;; The historical fallback wraps implicit integral narrowing
                                  ;; only; it must not acquire checked source-cast semantics.
                                  (if (and (not (dtype/fp-dtype? source))
                                           (not (dtype/fp-dtype? target)))
                                    (scalar-conversion/policy source target :wrap)
                                    (scalar-conversion/policy source target))))
                              (decline! :cast-policy
                                        "scalar cast has no portable rounding and overflow policy"
                                        {:expression expression :source source :target target})))
                        checked-floating? (and (dtype/fp-dtype? source) (= :trap overflow))
                        total-floating? (and checked-floating?
                                             (total-source-cast-literal? lowered explicit-source-op))
                        _ (when (and checked-floating? (not total-floating?))
                            (decline! :checked-floating-conversion
                                      "checked floating source conversion requires an ordered host observation"
                                      {:expression expression :source source :target target}))
                        overflow (if total-floating?
                                   (second (scalar-conversion/policy source target :trap)) overflow)
                        id (fresh "cast")]
                    (let [range (when (scalar-range/contained-in-dtype? (:range lowered) target)
                                  (:range lowered))]
                      (remember-range! id (or range (scalar-range/for-dtype target)))
                      {:operations (conj (:operations lowered)
                                       (body/->ScalarCompute
                                        (body/value id target)
                                        (body/cast-expression (:result lowered) target
                                                              rounding overflow)))
                       :result id :type target :range (or range (scalar-range/for-dtype target))})))))

            (lower-ordered-bindings
              [bindings env resolve-binding-type mismatch-rule mismatch-message]
              (reduce
               (fn [{:keys [operations substitutions environment]} [id init]]
                 (let [init (util/subst-syms substitutions init)
                       binding-type (canon-type (resolve-binding-type id init environment))
                       ;; A retained lexical binder can own a conditional join even
                       ;; when its alternatives have different source widths. Prove
                       ;; those widths independently and permit only exact widening;
                       ;; the existing branch lowerer preserves each operation's
                       ;; width and converts only the selected result at the join.
                       ;; An enclosing consumer hint is not a lexical contract.
                       init (if (and (retained-type id)
                                     (nil? (retained-type init))
                                     (seq? init) (= 'if (first init)) (= 4 (count init))
                                     (nil? (authoritative-source-type init environment))
                                     (every?
                                      (fn [branch]
                                        (when-let [source (authoritative-source-type branch environment)]
                                          (or (= (canon-type source) binding-type)
                                              (and (dtype/known? source)
                                                   (dtype/known? binding-type)
                                                   (= [:exact :exact]
                                                      (scalar-conversion/policy
                                                       (canon-type source) binding-type))))))
                                      [(nth init 2) (nth init 3)]))
                              (normalized-form init binding-type init)
                              init)
                       lowered (lower init binding-type environment)
                       _ (when-not (= binding-type (:type lowered))
                           (decline! mismatch-rule mismatch-message
                                     {:binding id :initializer init
                                      :expected binding-type :actual (:type lowered)}))
                       result (:result lowered)
                       ;; Substituted SSA references retain their definition dtype for subsequent
                       ;; source expressions and storage-coordinate lowering.
                       tag (when-not (= :predicate binding-type)
                             (:scalar-tag (dtype/info binding-type)))
                       result (if (and (symbol? result) tag)
                                (with-meta result
                                  (assoc (meta result) :raster.type/tag tag))
                                result)]
                   {:operations (into operations (:operations lowered))
                    :substitutions (assoc substitutions id result)
                    :environment (cond-> environment
                                   (symbol? result) (assoc result binding-type))}))
               {:operations [] :substitutions {} :environment env}
               (partition 2 bindings)))

            (lower-product-results [expressions result-types env]
              (let [expressions (vec expressions)
                    result-types (mapv canon-type result-types)
                    common-let?
                    (and (seq expressions)
                         (every? #(and (seq? %)
                                       (contains? #{'let 'let* 'clojure.core/let} (first %))
                                       (= 3 (count %)))
                                 expressions)
                         (apply = (map second expressions)))
                    common-if?
                    (and (seq expressions)
                         (every? #(and (seq? %) (= 'if (first %)) (= 4 (count %)))
                                 expressions)
                         (apply = (map second expressions)))]
                (cond
                  common-let?
                  (let [bindings (second (first expressions))
                        {:keys [operations substitutions environment]}
                        (lower-ordered-bindings
                         bindings env
                         (fn [id init environment]
                           (or (retained-type id)
                               (authoritative-source-type init environment)
                               (decline! :typed-product-fold-local-dtype
                                         "shared product Fold binding lacks a retained dtype"
                                         {:binding id :initializer init})))
                         :typed-product-fold-local-dtype
                         "shared product Fold binding must preserve its retained dtype")
                        tails (mapv #(util/subst-syms substitutions (nth % 2)) expressions)
                        lowered (lower-product-results tails result-types environment)]
                    (update lowered :operations #(into operations %)))

                  common-if?
                  (let [condition-expression (second (first expressions))
                        constant? (or (nil? condition-expression) (boolean? condition-expression)
                                      (keyword? condition-expression) (number? condition-expression)
                                      (string? condition-expression) (char? condition-expression))]
                    (if constant?
                      (lower-product-results
                       (mapv #(nth % (if (or (nil? condition-expression)
                                             (false? condition-expression)) 3 2))
                             expressions)
                       result-types env)
                      (let [condition (lower condition-expression :predicate env)
                            then-region (lower-product-results (mapv #(nth % 2) expressions)
                                                               result-types env)
                            else-region (lower-product-results (mapv #(nth % 3) expressions)
                                                               result-types env)
                            results (mapv (fn [_] (fresh "product-fold-if")) result-types)
                            ranges (mapv scalar-range/hull
                                         (map vector (:ranges then-region) (:ranges else-region)))]
                        (doseq [[result range] (map vector results ranges)]
                          (remember-range! result range))
                        {:operations
                         (conj (vec (:operations condition))
                               (body/->IfRegion
                                (:result condition)
                                (conj (vec (:operations then-region))
                                      (body/->Yield (:results then-region)))
                                (conj (vec (:operations else-region))
                                      (body/->Yield (:results else-region)))
                                (mapv (fn [result type] (body/value result type))
                                      results result-types)))
                         :results results :types result-types :ranges ranges})))

                  :else
                  (let [lowered (mapv (fn [expression type] (lower expression type env))
                                      expressions result-types)]
                    (doseq [[value type expression]
                            (map vector lowered result-types expressions)]
                      (when-not (= type (:type value))
                        (decline! :typed-product-fold-dtype
                                  "product Fold carry dtype must remain invariant"
                                  {:expression expression :expected type :actual (:type value)})))
                    {:operations (vec (mapcat :operations lowered))
                     :results (mapv :result lowered)
                     :types (mapv :type lowered)
                     :ranges (mapv :range lowered)}))))

            (lower-let [expression expected env]
              (let [[_ bindings & body-expressions] expression
                    ids (when (vector? bindings) (take-nth 2 bindings))]
                (when-not (and (vector? bindings) (even? (count bindings))
                               (every? symbol? ids) (= (count ids) (count (set ids)))
                               (= 1 (count body-expressions)))
                  (decline! :scalar-let-shape
                            "scalar let requires distinct ordered bindings and one result"
                            {:expression expression :bindings bindings
                             :body-count (count body-expressions)}))
                (let [{:keys [operations substitutions environment]}
                      (lower-ordered-bindings
                       bindings env
                       (fn [id init environment]
                         (or (retained-type id)
                             (authoritative-source-type init environment)
                             (decline! :scalar-let-binding-dtype
                                       "scalar let binding lacks an authoritative source dtype"
                                       {:binding id :initializer init
                                        :environment (set (keys environment))})))
                       :scalar-let-binding-dtype
                       "scalar let initializer disagrees with its retained dtype")
                      result-expression (util/subst-syms substitutions (first body-expressions))
                      result (lower result-expression expected environment)
                      result (if (= expected (:type result))
                               result
                               (cast-lowered result expected expression))]
                  (update result :operations #(into operations %)))))

            (lower [expression expected env]
              (let [lexical-let? (and (seq? expression)
                                      (contains? #{'let 'let* 'clojure.core/let} (first expression)))
                    ;; Strict typed owners preserve operation width before any consumer cast.
                    ;; Older packed owners retain their explicit widened-integer policy.
                    expected (canon-type expected)
                    _ (when (and require-source-types? (seq? expression) (not lexical-let?))
                        (source-type expression expected env))
                    retained (retained-type expression)
                    source-result-type (when require-source-types?
                                         (authoritative-source-type expression env))
                    operation-type (if (or source-result-type
                                           (and retained
                                                (dtype/fp-dtype? expected)
                                                (dtype/fp-dtype? retained)))
                                     (or source-result-type retained)
                                     expected)
                    lowered (if lexical-let?
                              (lower-let expression operation-type env)
                              (lower-value expression operation-type env))]
                ;; Loads and explicit source conversions retain their own result dtype. The
                ;; consumer boundary must convert that actual result, not the requested hint.
                (if (not= (:type lowered) expected)
                  (cast-lowered lowered expected expression)
                  lowered)))

            (lower-value [expression expected env]
                (cond
                  (instance? raster.compiler.ir.kernel_body.Literal expression)
                  {:operations [] :result expression
                   :type (canon-type (:type expression))
                   :range (scalar-range/literal (:value expression) (:type expression))}

                  (and (= :predicate expected) (number? expression))
                  (if (contains? #{0 1} expression)
                    {:operations [] :result (body/literal (= 1 expression) :predicate)
                     :type :predicate}
                    (decline! :predicate-literal
                              "numeric predicates must use the canonical zero/one encoding"
                              {:expression expression}))

                  (number? expression)
                  (let [range (scalar-range/literal expression expected)]
                    {:operations [] :result (body/literal expression expected)
                     :type expected :range range})

                  (boolean? expression)
                  {:operations [] :result (body/literal expression :predicate) :type :predicate}

                  (symbol? expression)
                  (if-let [actual (or (get env expression) (get scalar-types expression))]
                    (let [type (canon-type actual)]
                      {:operations [] :result expression :type type
                       :range (known-range expression type)})
                    (if-let [constant (numeric-constant/value expression)]
                      (lower-value (:value constant) expected env)
                      (decline! :unbound-scalar
                                "scalar expression references an undeclared value"
                                {:expression expression :environment (set (keys env))})))

                  (descriptor/aget-call? expression)
                  (let [array (descriptor/aget-array-sym expression)
                        arguments (vec (descriptor/call-args expression))
                        coordinate (last arguments)
                        array-type (some-> (get array-types array) dtype/canon)]
                    (when-not (and (= 2 (count arguments)) (contains? arrays array) array-type)
                      (decline! :indexed-load
                                "scalar loads require a declared typed stable tensor"
                                {:expression expression :array array :array-types array-types}))
                    (if owner-load-coordinates
                      ;; Closed layout regions own coordinates independently of the retained
                      ;; source spelling. Never evaluate that spelling as a second index authority.
                      (load-ssa array (owner-load-coordinates array))
                    (let [coordinate-value
                          (when (or (contains-indexed-load? coordinate)
                                    (index-expression/requires-scalar-evaluation? coordinate))
                            ;; Materialize nested loads and source-width wrapping arithmetic as
                            ;; typed scalar SSA before using the result as a storage coordinate.
                            ;; The final coordinate widens; its inner int operation must not.
                            (lower coordinate :long env))
                          coordinate-expression
                          (if coordinate-value
                            (:result coordinate-value)
                            (lower-load-index array coordinate (set (keys env))))
                          loaded (load-ssa array [coordinate-expression])]
                      (update loaded :operations #(into (vec (:operations coordinate-value)) %)))))

                  (and (seq? expression) (descriptor/cast-op? (first expression))
                       (= 2 (count expression)))
                  (let [target (dtype/dtype-for-scalar-tag
                                (descriptor/cast-result-tag (first expression)))
                        operand (second expression)
                        ;; A conditional need not have one source dtype, including when one
                        ;; branch is itself a mixed-type conditional. Cast only the selected
                        ;; branch, exactly as the source cast does. Recursive distribution keeps
                        ;; each leaf's retained dtype authoritative and evaluates each condition
                        ;; once; it never guesses a union type from the destination.
                        conditional? (and (seq? operand) (= 'if (first operand))
                                          (= 4 (count operand)))]
                    (if conditional?
                      (lower (list 'if (second operand)
                                   (list (first expression) (nth operand 2))
                                   (list (first expression) (nth operand 3)))
                             target env)
                      (let [source-expected
                            (dtype/canon
                             (or (authoritative-source-type operand env)
                                 (decline! :scalar-source-type
                                           "explicit scalar cast requires the retained operand dtype"
                                           {:expression expression :operand operand
                                            :target target})))
                            lowered (lower operand source-expected env)]
                        (cast-lowered lowered target expression (first expression)))))

                  (dialect/scalar-convert-form? expression)
                  (let [{:keys [attributes operand]} (dialect/scalar-convert-parts expression)
                        {:keys [source-dtype target-dtype rounding overflow]} attributes
                        _ (when-not (and (dialect/scalar-convert-attributes? attributes)
                                         (= (canon-type target-dtype) expected))
                            (decline! :typed-scalar-convert
                                      "typed scalar conversion must match its consumer dtype"
                                      {:expression expression :expected expected
                                       :attributes attributes}))
                        lowered (lower operand (canon-type source-dtype) env)
                        checked-floating? (and (dtype/fp-dtype? source-dtype) (= :trap overflow))
                        total-floating? (and checked-floating?
                                             (total-source-cast-literal? lowered (:source-op attributes)))
                        _ (when (and checked-floating? (not total-floating?))
                            (decline! :checked-floating-conversion
                                      "checked floating source conversion requires an ordered host observation"
                                      {:expression expression :source source-dtype :target target-dtype}))
                        overflow (if total-floating?
                                   (second (scalar-conversion/policy source-dtype target-dtype :trap))
                                   overflow)
                        _ (when-not (= (canon-type source-dtype) (:type lowered))
                            (decline! :typed-scalar-convert-source
                                      "typed scalar conversion operand disagrees with its source dtype"
                                      {:expression expression :expected source-dtype
                                       :actual (:type lowered)}))]
                    (if (= (canon-type source-dtype) (canon-type target-dtype))
                      lowered
                      (let [range (when (scalar-range/contained-in-dtype?
                                         (:range lowered) target-dtype)
                                    (:range lowered))
                            overflow (if (and (= :trap overflow) range) :exact overflow)
                            id (fresh "convert")]
                        (remember-range! id (or range (scalar-range/for-dtype target-dtype)))
                        {:operations
                         (conj (:operations lowered)
                               (body/->ScalarCompute
                                (body/value id target-dtype)
                                (body/cast-expression (:result lowered) target-dtype
                                                      rounding overflow)))
                         :result id :type target-dtype
                         :range (or range (scalar-range/for-dtype target-dtype))})))

                  (and (seq? expression)
                       (= 'raster.numeric/oftype (descriptor/semantic-op expression))
                       (= 2 (count (descriptor/call-args expression))))
                  (let [value-expression (second (descriptor/call-args expression))
                        source-expected (canon-type (source-type value-expression expected env))
                        lowered (lower value-expression source-expected env)]
                    (cast-lowered lowered expected expression))

                  (and (seq? expression) (= 'if (first expression)) (= 4 (count expression)))
                  (let [[_ condition then-expression else-expression] expression
                        constant-condition?
                        (or (nil? condition) (boolean? condition) (keyword? condition)
                            (number? condition) (string? condition) (char? condition))]
                    (if constant-condition?
                      ;; Clojure `cond` expands its default arm to `(if :else ...)`. Resolve
                      ;; literal truthiness before entering KernelBody, whose predicates are
                      ;; deliberately boolean and must never inherit C-family zero semantics.
                      (lower (if (or (nil? condition) (false? condition))
                               else-expression then-expression)
                             expected env)
                      (let [condition (lower condition :predicate env)
                            then-value (lower then-expression expected env)
                            else-value (lower else-expression expected env)
                            result-type (:type then-value)
                            _ (when-not (= result-type (:type else-value) expected)
                                (decline! :branch-dtype
                                          "scalar branches must have one explicit result dtype"
                                          {:expression expression :then (:type then-value)
                                           :else (:type else-value) :expected expected}))
                            result (fresh "if")
                            range (scalar-range/hull [(:range then-value) (:range else-value)])]
                        (remember-range! result range)
                        {:operations
                         (conj (vec (:operations condition))
                               (body/->IfRegion
                                (:result condition)
                                (conj (vec (:operations then-value))
                                      (body/->Yield [(:result then-value)]))
                                (conj (vec (:operations else-value))
                                      (body/->Yield [(:result else-value)]))
                                [(body/value result result-type)]))
                         :result result :type result-type :range range})))

                  (and (seq? expression) (= 1 (count (descriptor/call-args expression)))
                       (contains? '#{pos? neg? zero? clojure.core/pos? clojure.core/neg?
                                     clojure.core/zero? raster.numeric/pos? raster.numeric/neg?
                                     raster.numeric/zero?}
                                  (descriptor/semantic-op expression)))
                  (let [source-operation (descriptor/semantic-op expression)
                        operator (case (name source-operation)
                                   "pos?" :gt "neg?" :lt "zero?" :eq)
                        ;; Walked deftm calls use `(.invk implementation operand)`, while direct
                        ;; source calls use `(zero? operand)`. The descriptor is the one canonical
                        ;; call-shape projection; raw `second` would mistake the implementation
                        ;; Var for the operand only on the walked path.
                        operand-expression (first (descriptor/call-args expression))
                        operand-type (canon-type
                                      (or (authoritative-source-type operand-expression env)
                                          (decline! :scalar-source-type
                                                    "numeric predicate requires a retained operand dtype"
                                                    {:expression expression
                                                     :operand operand-expression})))
                        operand (lower operand-expression operand-type env)
                        compared (compute-ssa operator :predicate
                                              [(:result operand)
                                               (body/literal 0 operand-type)] {} nil)]
                    (update compared :operations #(into (vec (:operations operand)) %)))

                  (dialect/scalar-fold-form? expression)
                  (let [{:keys [attributes lambda]} (dialect/scalar-fold-parts expression)
                        {parameters :parameters fold-locals :locals
                         body-results :body-results} (dialect/lambda-parts lambda)
                        [accumulator index] parameters
                        fold-type (canon-type (:dtype attributes))
                        _ (when-not (and (= 2 (count parameters))
                                         (= 1 (count body-results)))
                            (decline! :typed-scalar-fold-shape
                                      "canonical scalar fold requires one typed carry and result"
                                      {:expression expression :expected expected
                                       :dtype fold-type :parameters parameters
                                       :locals fold-locals :results body-results}))
                        loop-index (fresh "fold-index")
                        carry (fresh "fold-carry")
                        result (fresh "fold-result")
                        initial (lower (:identity attributes) fold-type env)
                        lower-bound (lower-index (:lower attributes 0) (set (keys env)))
                        upper-bound (lower-index (:extent attributes) (set (keys env)))
                        loop-body
                        (with-fold-index-range
                         loop-index lower-bound upper-bound
                         (:upper-bound attributes :exclusive) env
                         (fn []
                           (let [local-state
                                 (reduce
                                  (fn [{:keys [operations substitutions environment]} local]
                                    (let [local-type (canon-type (:dtype local))
                                          local-expression (util/subst-syms substitutions (:init local))
                                          lowered (lower local-expression local-type environment)
                                          local-result (:result lowered)
                                          tag (:scalar-tag (dtype/info local-type))
                                          local-result (if (and (symbol? local-result) tag)
                                                         (with-meta local-result
                                                           (assoc (meta local-result)
                                                                  :raster.type/tag tag))
                                                         local-result)]
                                      (when-not (= local-type (:type lowered))
                                        (decline! :typed-scalar-fold-local-dtype
                                                  "canonical Fold local must preserve its retained dtype"
                                                  {:expression expression :local local
                                                   :actual (:type lowered)}))
                                      {:operations (into operations (:operations lowered))
                                       :substitutions (assoc substitutions (:id local) local-result)
                                       :environment (cond-> environment
                                                      (symbol? local-result)
                                                      (assoc local-result local-type))}))
                                  {:operations []
                                   :substitutions {index loop-index accumulator carry}
                                   :environment (assoc env loop-index :long carry fold-type)}
                                  fold-locals)
                                 update-expression (util/subst-syms (:substitutions local-state)
                                                                   (first body-results))
                                 update (lower update-expression fold-type (:environment local-state))]
                             {:local-state local-state :update update})))
                        local-state (:local-state loop-body)
                        update (:update loop-body)
                        _ (when-not (= fold-type (:type initial) (:type update))
                            (decline! :typed-scalar-fold-dtype
                                      "canonical scalar fold carry dtype must remain invariant"
                                      {:expression expression :initial (:type initial)
                                       :update (:type update) :dtype fold-type}))
                        loop-operation
                        (body/->ForLoop
                         (body/value loop-index :long)
                         lower-bound
                         upper-bound
                         1
                         [(body/->LoopArg (body/value carry fold-type) (:result initial))]
                         (conj (into (vec (:operations local-state)) (:operations update))
                               (body/->Yield [(:result update)]))
                         [(body/value result fold-type)]
                         (cond-> {:association (:association attributes)
                                  :source-order (= :ordered (:association attributes))}
                           (= :inclusive (:upper-bound attributes))
                           (assoc :upper-bound :inclusive)
                           (:algebra attributes) (assoc :algebra (:algebra attributes))))]
                    (let [computed {:operations (conj (vec (:operations initial)) loop-operation)
                                    :result result :type fold-type}]
                      ;; Consumer/storage precision does not change the declared carry. Convert
                      ;; only the completed result, using the same conversion authority as SSA ops.
                      (if (or (nil? expected) (= fold-type (canon-type expected)))
                        computed
                        (cast-lowered computed expected expression))))

                  (dialect/product-component-form? expression)
                  (let [[_ product ordinal] expression
                        cached (get @product-fold-cache product)
                        first-use? (nil? cached)
                        lowered-product
                        (or cached
                            (let [{:keys [attributes lambda]}
                                  (dialect/product-fold-parts product)
                                  {parameters :parameters fold-locals :locals
                                   body-results :body-results} (dialect/lambda-parts lambda)
                                  accumulators (:accumulators attributes)
                                  index (:index attributes)
                                  dtypes (mapv canon-type (:dtypes attributes))
                                  identities (:identities attributes)
                                  _ (when-not (and (= parameters (conj accumulators index))
                                                   (= (count accumulators) (count identities)
                                                      (count dtypes) (count body-results)))
                                      (decline! :typed-product-fold-shape
                                                "product Fold parameters, identities, dtypes and results must align"
                                                {:expression expression :parameters parameters
                                                 :accumulators accumulators
                                                 :results body-results}))
                                  loop-index (fresh "product-fold-index")
                                  carries (mapv (fn [_] (fresh "product-fold-carry")) accumulators)
                                  results (mapv (fn [_] (fresh "product-fold-result")) accumulators)
                                  initials (mapv (fn [identity type] (lower identity type env))
                                                 identities dtypes)
                                  initial-env (into (assoc env loop-index :long)
                                                    (map vector carries dtypes))
                                  substitutions (into {index loop-index}
                                                      (map vector accumulators carries))
                                  local-state
                                  (reduce
                                   (fn [{:keys [operations substitutions environment]} local]
                                     (let [local-type (canon-type (:dtype local))
                                           local-expression (util/subst-syms substitutions (:init local))
                                           lowered (lower local-expression local-type environment)]
                                       (when-not (= local-type (:type lowered))
                                         (decline! :typed-product-fold-local-dtype
                                                   "product Fold local must preserve its retained dtype"
                                                   {:expression expression :local local
                                                    :actual (:type lowered)}))
                                       {:operations (into operations (:operations lowered))
                                        :substitutions (assoc substitutions (:id local) (:result lowered))
                                        :environment (cond-> environment
                                                       (symbol? (:result lowered))
                                                       (assoc (:result lowered) local-type))}))
                                   {:operations [] :substitutions substitutions
                                    :environment initial-env}
                                   fold-locals)
                                  updates
                                  (lower-product-results
                                   (mapv #(util/subst-syms (:substitutions local-state) %)
                                         body-results)
                                   dtypes (:environment local-state))
                                  loop-operation
                                  (body/->ForLoop
                                   (body/value loop-index :long)
                                   (lower-index (:lower attributes 0) (set (keys env)))
                                   (lower-index (:extent attributes) (set (keys env)))
                                   1
                                   (mapv (fn [carry initial]
                                           (body/->LoopArg (body/value carry (:type initial))
                                                           (:result initial)))
                                         carries initials)
                                   (conj (into (vec (:operations local-state))
                                               (:operations updates))
                                         (body/->Yield (:results updates)))
                                   (mapv (fn [result type] (body/value result type)) results dtypes)
                                   (cond-> {:association :ordered :source-order true}
                                     (= :inclusive (:upper-bound attributes))
                                     (assoc :upper-bound :inclusive)))
                                  lowered {:operations (conj (vec (mapcat :operations initials))
                                                             loop-operation)
                                           :results results :types dtypes}]
                              (swap! product-fold-cache assoc product lowered)
                              lowered))
                        _ (when-not (< -1 ordinal (count (:results lowered-product)))
                            (decline! :typed-product-fold-component
                                      "product Fold component ordinal is outside its result tuple"
                                      {:expression expression :ordinal ordinal}))]
                    {:operations (if first-use? (:operations lowered-product) [])
                     :result (nth (:results lowered-product) ordinal)
                     :type (nth (:types lowered-product) ordinal)})

                  (dialect/while-component-form? expression)
                  (let [[_ while-fold ordinal] expression
                        cached (get @product-fold-cache while-fold)
                        first-use? (nil? cached)
                        lowered-loop
                        (or cached
                            (let [{:keys [attributes condition update]}
                                  (dialect/while-fold-parts while-fold)
                                  accumulators (:accumulators attributes)
                                  dtypes (mapv canon-type (:dtypes attributes))
                                  condition-region (dialect/lambda-parts condition)
                                  update-region (dialect/lambda-parts update)
                                  _ (when-not (and (= accumulators (:parameters condition-region)
                                                     (:parameters update-region))
                                                   (empty? (:locals condition-region))
                                                   (empty? (:locals update-region))
                                                   (= 1 (count (:body-results condition-region)))
                                                   (= (count accumulators)
                                                      (count (:body-results update-region))))
                                      (decline! :typed-while-fold-shape
                                                "while fold regions must agree with typed carries"
                                                {:expression expression}))
                                  initials (mapv (fn [identity type] (lower identity type env))
                                                 (:identities attributes) dtypes)
                                  carries (mapv (fn [_] (fresh "while-carry")) accumulators)
                                  results (mapv (fn [_] (fresh "while-result")) accumulators)
                                  substitutions (zipmap accumulators carries)
                                  loop-env (into env (map vector carries dtypes))
                                  condition-expression
                                  (util/subst-syms substitutions
                                                   (first (:body-results condition-region)))
                                  condition-value (lower condition-expression :predicate loop-env)
                                  update-expressions
                                  (mapv #(util/subst-syms substitutions %)
                                        (:body-results update-region))
                                  updates (lower-product-results update-expressions dtypes loop-env)
                                  operation
                                  (body/->WhileLoop
                                   (mapv (fn [carry initial]
                                           (body/->LoopArg (body/value carry (:type initial))
                                                           (:result initial)))
                                         carries initials)
                                   (conj (vec (:operations condition-value))
                                         (body/->Yield [(:result condition-value)]))
                                   (conj (vec (:operations updates))
                                         (body/->Yield (:results updates)))
                                   (mapv (fn [result type] (body/value result type)) results dtypes)
                                   {:association :ordered :source-order true})
                                  lowered {:operations (conj (vec (mapcat :operations initials))
                                                             operation)
                                           :results results :types dtypes}]
                              (swap! product-fold-cache assoc while-fold lowered)
                              lowered))]
                    (when-not (< -1 ordinal (count (:results lowered-loop)))
                      (decline! :typed-while-fold-component
                                "while fold component ordinal is outside its carried tuple"
                                {:expression expression :ordinal ordinal}))
                    {:operations (if first-use? (:operations lowered-loop) [])
                     :result (nth (:results lowered-loop) ordinal)
                     :type (nth (:types lowered-loop) ordinal)})

                  (and (seq? expression) (contains? #{'loop 'loop*} (first expression)))
                  (if-let [{:keys [acc-sym acc-init index-sym bound-expr else-expr update-expr
                                   inclusive? index-init]}
                           (match-ordered-loop expression)]
                    (do
                      (when (or (patterns/contains-sym? bound-expr index-sym)
                                (patterns/contains-sym? bound-expr acc-sym)
                                (patterns/contains-sym? else-expr index-sym))
                        (decline! :ordered-loop-shape
                                  "ordered scalar loop requires an invariant upper bound and an exit over its carry"
                                  {:expression expression :bound bound-expr
                                   :index index-sym :accumulator acc-sym :exit else-expr}))
                      (let [loop-index (fresh "loop-index")
                            carry (fresh "loop-carry")
                            result (fresh "loop-result")
                            ;; `(loop [i 0 s init] (if (< i n) (recur (inc i) step) exit))` is the
                            ;; ordered fold followed by `exit` over the final carry. The carry keeps
                            ;; the step's own dtype so the exit's cast (e.g. `(double s)`) is an
                            ;; explicit conversion rather than a silent widening of the fold.
                            exit? (not= else-expr acc-sym)
                            initial-source-type (authoritative-source-type acc-init env)
                            carry-source-env (cond-> (assoc env index-sym :long)
                                               initial-source-type
                                               (assoc acc-sym (canon-type initial-source-type)))
                            carry-type (if exit?
                                         (canon-type
                                          (or (authoritative-source-type
                                               update-expr carry-source-env)
                                              (source-type update-expr expected
                                                           carry-source-env)))
                                         expected)
                            initial (lower acc-init carry-type env)
                            loop-type (:type initial)
                            update (util/subst-syms {index-sym loop-index acc-sym carry}
                                                    update-expr)
                            lowered (lower update loop-type
                                           (assoc env loop-index :long carry loop-type))
                            _ (when-not (= loop-type (:type lowered))
                                (decline! :ordered-loop-dtype
                                          "ordered scalar loop carry dtype must remain invariant"
                                          {:expression expression :initial loop-type
                                           :update (:type lowered)}))
                            upper (lower-index bound-expr (set (keys env)))
                            loop (body/->ForLoop
                                  (body/value loop-index :long)
                                  (body/index-cast index-init :long :exact)
                                  upper 1
                                  [(body/->LoopArg (body/value carry loop-type)
                                                   (:result initial))]
                                  (conj (vec (:operations lowered))
                                        (body/->Yield [(:result lowered)]))
                                  [(body/value result loop-type)]
                                  (cond-> {:association :ordered}
                                    inclusive? (assoc :upper-bound :inclusive)))
                            exit (when exit?
                                   (lower (util/subst-syms {acc-sym result} else-expr)
                                          expected (assoc env result loop-type)))]
                        (if exit
                          {:operations (into (conj (vec (:operations initial)) loop)
                                             (:operations exit))
                           :result (:result exit) :type (:type exit)}
                          {:operations (conj (vec (:operations initial)) loop)
                           :result result :type loop-type})))
                    (decline! :ordered-loop-shape
                              "scalar loop is outside the canonical ordered carry form"
                              {:expression expression}))

                  ;; `inc`/`dec` are the closed-core index steppers: `(+ x 1)` / `(- x 1)` with the
                  ;; same operand dtype and overflow policy. Normalize before intrinsic lookup so
                  ;; the KernelBody vocabulary stays binary.
                  (and (seq? expression) (= 2 (count expression))
                       (contains? '#{inc clojure.core/inc} (first expression)))
                  (lower (normalized-form (list 'clojure.core/+ (second expression) 1)
                                          expected expression) expected env)

                  (and (seq? expression) (= 2 (count expression))
                       (contains? '#{dec clojure.core/dec} (first expression)))
                  (lower (normalized-form (list 'clojure.core/- (second expression) 1)
                                          expected expression) expected env)

                  ;; Unchecked steppers carry modular integral semantics. Route
                  ;; through the existing wrapping binary intrinsic rather than
                  ;; treating them as checked Clojure inc/dec or inventing a
                  ;; target-specific unary operation.
                  (and (seq? expression) (= 2 (count expression))
                       (contains? '#{unchecked-inc clojure.core/unchecked-inc}
                                  (first expression)))
                  (lower (normalized-form
                          (list 'clojure.core/unchecked-add (second expression) 1)
                          expected expression) expected env)

                  (and (seq? expression) (= 2 (count expression))
                       (contains? '#{unchecked-dec clojure.core/unchecked-dec}
                                  (first expression)))
                  (lower (normalized-form
                          (list 'clojure.core/unchecked-subtract (second expression) 1)
                          expected expression) expected env)

                  ;; Unary subtraction is the existing negation intrinsic for floating values:
                  ;; spelling it as 0-x would lose the sign of zero. Integral negation instead
                  ;; uses the checked/wrapping subtraction machinery, including MIN_VALUE.
                  (and (seq? expression)
                       (= :- (intrinsics/canonical (descriptor/semantic-op expression)))
                       (= 1 (count (descriptor/call-args expression))))
                  (lower (normalized-form (if (dtype/fp-dtype? expected)
                           (list :neg (first (descriptor/call-args expression)))
                           (list (descriptor/semantic-op expression)
                                 (body/literal 0 expected)
                                 (first (descriptor/call-args expression)))) expected expression)
                         expected env)

                  (and (seq? expression)
                       (= :java-round (:typed-expansion
                                       (intrinsics/descriptor
                                        (intrinsics/canonical (descriptor/semantic-op expression))))))
                  (let [arguments (vec (descriptor/call-args expression))
                        intrinsic (intrinsics/descriptor
                                   (intrinsics/canonical (descriptor/semantic-op expression)))
                        _ (when-not (= 1 (count arguments))
                            (decline! :scalar-expression "Java round requires one argument"
                                      {:expression expression}))
                        input-type (source-type (first arguments) nil env)
                        result-type (get (:source-signatures intrinsic) input-type)
                        _ (when-not result-type
                            (decline! :scalar-source-type "Java round requires a retained floating overload"
                                      {:expression expression :source input-type}))
                        input (lower (first arguments) input-type env)
                        base (compute-ssa :floor input-type [(:result input)] {} nil)
                        fraction (compute-ssa :- input-type [(:result input) (:result base)] {} nil)
                        up (compute-ssa :ge :predicate [(:result fraction) (body/literal 0.5 input-type)] {} nil)
                        next (compute-ssa :+ input-type [(:result base) (body/literal 1.0 input-type)] {} nil)
                        rounded (compute-ssa :select input-type [(:result up) (:result next) (:result base)] {} nil)
                        converted (compute-ssa :cast result-type [(:result rounded)]
                                               {:rounding :toward-zero :overflow :saturate} nil)]
                    ;; Adding 0.5 before floor would double-round the predecessor of 0.5.
                    ;; Saturation supplies Java's NaN=0 and signed endpoint semantics.
                    (cast-lowered (assoc converted :operations
                                         (vec (mapcat :operations
                                                      [input base fraction up next rounded converted])))
                                  expected expression))

                  (and (seq? expression)
                       (= :source-signum
                          (:typed-expansion
                           (intrinsics/descriptor
                            (intrinsics/canonical (descriptor/semantic-op expression))))))
                  (let [arguments (vec (descriptor/call-args expression))
                        _ (when-not (= 1 (count arguments))
                            (decline! :scalar-expression "signum requires one argument"
                                      {:expression expression}))
                        input-type (canon-type
                                    (or (authoritative-source-type (first arguments) env)
                                        (decline! :scalar-source-type
                                                  "signum requires a retained operand dtype"
                                                  {:expression expression})))
                        input (lower (first arguments) input-type env)
                        positive? (compute-ssa :gt :predicate
                                               [(:result input) (body/literal 0 input-type)] {} nil)
                        negative? (compute-ssa :lt :predicate
                                               [(:result input) (body/literal 0 input-type)] {} nil)
                        negative (compute-ssa :select input-type
                                              [(:result negative?) (body/literal -1 input-type)
                                               (:result input)] {} nil)
                        signed (compute-ssa :select input-type
                                            [(:result positive?) (body/literal 1 input-type)
                                             (:result negative)] {} nil)
                        signed (assoc signed :operations
                                      (vec (mapcat :operations
                                                   [input positive? negative? negative signed])))]
                    (if (= input-type expected)
                      signed
                      (cast-lowered signed expected expression)))

                  (seq? expression)
                  (let [semantic-operation (descriptor/semantic-op expression)
                        operator (intrinsics/canonical semantic-operation)
                        intrinsic (intrinsics/descriptor operator)
                        arguments (vec (descriptor/call-args expression))
                        ;; A selected implementation is not authenticated by
                        ;; its nominal arithmetic name. Keep argument evaluation
                        ;; and completion separate from this callee-only check.
                        selected-operation? (and method-entry/*emission-inputs*
                                     (= '.invk (first expression))
                                     (= :infix (:kind intrinsic))
                                     (source-arithmetic/binary-operator? (:c intrinsic))
                                     (= 2 (count arguments))
                                     (dtype/fp-dtype? expected))
                        selected-operation (when selected-operation?
                                             (canonical-selected-fp-operation expression))
                        _ (when (and selected-operation? (nil? selected-operation))
                            (decline! :selected-scalar-source-correspondence
                                      "selected scalar body does not attest the emitted canonical operation"
                                      {:expression expression :operator operator}))]
                    (when-not intrinsic
                      (decline! :scalar-expression
                                "scalar expression has no canonical intrinsic"
                                {:expression expression :operator operator}))
                    (if (ordered-fold-intrinsic? intrinsic operator (count arguments))
                      ;; Preserve source evaluation order while spelling variadic scalar folds in
                      ;; the binary KernelBody vocabulary. This is normalization, not algebraic
                      ;; reassociation: `(- a b c)` becomes `(- (- a b) c)`.
                      (lower (reduce (fn [left right]
                                       (normalized-form (list (descriptor/semantic-op expression) left right)
                                                        expected expression))
                                     arguments)
                             expected env)
                      (do
                        (when-not (= (:arity intrinsic) (count arguments))
                          (decline! :scalar-expression
                                    "scalar expression has the wrong intrinsic arity"
                                    {:expression expression :operator operator
                                     :expected (:arity intrinsic)
                                     :actual (count arguments)}))
                        (let [comparison? (= :cmp (:kind intrinsic))
                              ;; An enclosing consumer dtype is not the source arithmetic dtype.
                              ;; When operand facts determine a checked Long addition feeding a
                              ;; Float stage, compute the addition as Long and convert its result;
                              ;; converting operands first changes both overflow and rounding.
                              source-result-type
                              (when-not comparison?
                                (dtype/canon (source-type expression expected env)))
                              ;; Correspondence includes widths, not just the operator.
                              ;; Until entry conversions have their own source-completion
                              ;; proof, accept only already matching primitive operands.
                              ;; In particular a Double result stamp must not erase an
                              ;; actual Float helper's rounding checkpoint.
                              _ (when selected-operation
                                  (let [carrier-dtype #(dtype/dtype-for-scalar-tag
                                                       (symbol (.getName ^Class %)))
                                        payload-type (carrier-dtype (:payload-carrier selected-operation))
                                        formal-types (mapv carrier-dtype
                                                           (:parameter-carriers selected-operation))
                                        argument-types (mapv #(some-> (authoritative-source-type % env)
                                                                      dtype/canon)
                                                             arguments)]
                                    (when-not (and (= payload-type source-result-type)
                                                   (= formal-types argument-types)
                                                   (every? #{payload-type} formal-types))
                                      (decline! :selected-scalar-source-width
                                                "selected scalar widths require source-owned entry and result conversions"
                                                {:expression expression :payload-type payload-type
                                                 :source-result-type source-result-type
                                                 :formal-types formal-types
                                                 :argument-types argument-types}))))
                              operand-type (if comparison?
                                             (let [types (mapv #(some-> (authoritative-source-type % env)
                                                                       dtype/canon)
                                                               arguments)]
                                               (if (every? #{:int :long :float :double} types)
                                                 (apply source-arithmetic/comparison-carrier types)
                                                 (dtype/canon
                                                  (or (source-type (first arguments) :int env) :int))))
                                             source-result-type)
                              lowered (mapv #(cast-lowered
                                              (lower % operand-type env)
                                              operand-type expression)
                                            arguments)
                              result-type (if comparison? :predicate source-result-type)
                              ;; Typed source arithmetic has a semantic overflow contract: normal
                              ;; Clojure integral arithmetic is checked, while the explicitly
                              ;; `unchecked-*` forms wrap.  Retain that distinction in KernelBody
                              ;; rather than leaving a C-family emitter to choose signed overflow.
                              integral-arithmetic?
                              (and (contains? #{:byte :int :long} operand-type)
                                   (contains? #{:+ :- :*} operator))
                              operand-ranges (mapv :range lowered)
                              proven-range (when integral-arithmetic?
                                             (scalar-range/arithmetic operator operand-ranges))
                              overflow (when integral-arithmetic?
                                         (or (intrinsics/source-overflow-policy semantic-operation)
                                             (when (scalar-range/contained-in-dtype? proven-range operand-type)
                                               :no-overflow)
                                             :trap))
                              options (cond-> {} overflow (assoc :overflow overflow)
                                               (= :no-overflow overflow)
                                               (assoc :proof (assoc proven-range
                                                              :kind :typed-scalar-range)))
                              _ (when-not (every? #(= operand-type (:type %)) lowered)
                                  (decline! :operand-dtype
                                            "scalar intrinsic operands require one dtype"
                                            {:expression expression :operand-type operand-type
                                             :actual (mapv :type lowered)}))
                              result-range (if (= :quot operator)
                                             (scalar-range/quotient operand-ranges)
                                             proven-range)
                              computed (compute-ssa operator result-type (mapv :result lowered)
                                                    options (when (scalar-range/contained-in-dtype?
                                                                    result-range result-type)
                                                              result-range))
                              computed (update computed :operations
                                               #(into (vec (mapcat :operations lowered)) %))]
                          (if (or comparison? (nil? expected)
                                  (= result-type (dtype/canon expected)))
                            computed
                            (cast-lowered computed expected expression))))))

                  :else
                  (decline! :scalar-expression
                            "scalar expression has an unsupported value"
                            {:expression expression :type (type expression)})))]
      ;; Reserve at public region boundaries, not at every recursive child: identifiers are
      ;; scoped facts, and rescanning each subtree would make deeply nested lowering quadratic.
      {:fresh-binding fresh
       ;; Owners that must validate a source conversion without contributing a consumer dtype
       ;; may ask this same strict authority for the independently derived expression type.
       :source-type (fn [expression env]
                      (some-> (authoritative-source-type expression env) canon-type))
       :lower (fn [expression expected env]
                ;; A proved coordinate may introduce owner SSA names after source projection.
                (reserve! [expression (when-not (some? source-region) (keys env)) predicate])
                (lower expression expected env))
       :cast (fn [lowered target expression]
               (reserve! [lowered expression predicate])
               (cast-lowered lowered target expression))
       ;; These typed entries perform no source admission, index proof, promotion or overflow
       ;; inference. Their owner supplies proved coordinates and already-converted operands.
       :load load-ssa
       :compute (fn [operator result-type arguments options]
                  (compute-ssa operator result-type arguments options nil))
       :lower-region
       (fn [{:keys [bindings results]} result-types binding-types env]
         (reset! product-fold-cache {})
         ;; Later binders matter too: substitutions must never capture a generated earlier ID.
         (reserve! [bindings results (keys env) predicate])
         ;; Region locals are evaluated once, in source order. In particular, a product's
         ;; shared combine bindings must not be beta-expanded separately into every result.
         ;; Types are retained facts supplied by the caller, never guessed from a consumer.
         (when-not (and (vector? bindings) (even? (count bindings))
                        (every? symbol? (take-nth 2 bindings))
                        (= (count (take-nth 2 bindings))
                           (count (set (take-nth 2 bindings))))
                        (vector? results) (= (count results) (count result-types)))
           (decline! :scalar-region-shape
                     "scalar region requires distinct ordered bindings and typed results"
                     {:bindings bindings :results results :result-types result-types}))
         (let [checked-lower
               (fn [expression expected local-env]
                 (let [expected (canon-type expected)
                       lowered (lower expression expected local-env)]
                   (when-not (= expected (:type lowered))
                     (decline! :scalar-region-dtype
                               "scalar region value disagrees with its retained dtype"
                               {:expression expression :expected expected
                                :actual (:type lowered)}))
                   lowered))
               {:keys [operations substitutions environment]}
               (lower-ordered-bindings
                bindings env
                (fn [id expression _]
                  (or (get binding-types id)
                      (decline! :scalar-region-binding-dtype
                                "scalar region binding lacks a retained dtype"
                                {:binding id :expression expression})))
                :scalar-region-dtype
                "scalar region value disagrees with its retained dtype")
               lowered-results
               (mapv (fn [expression expected]
                       (checked-lower (util/subst-syms substitutions expression)
                                      expected environment))
                     results result-types)]
           {:operations (into operations (mapcat :operations lowered-results))
            :results (mapv :result lowered-results)
            :types (mapv :type lowered-results)}))})))

(defn- checked-scalar-program
  [expression scalar-types]
  (let [decline! (fn [rule message data]
                   (throw (ex-info message (assoc data :reason :primitive-presence-decline :rule rule))))
        lowerer (make-lowerer {:scalar-types scalar-types :array-types {} :arrays #{}
                              :index-scope #{} :source-region expression
                              :lower-index (fn [& _]
                                             (decline! :presence-index "Presence proof has no index owner" {}))
                              :require-source-types? true :decline! decline!})]
    (try
      (when-let [source-type ((:source-type lowerer) expression scalar-types)]
        (let [result ((:lower lowerer) expression source-type scalar-types)]
          (when (and (= source-type (:type result))
                     (or (= :predicate source-type) (dtype/info source-type)))
            result)))
      (catch clojure.lang.ExceptionInfo e
        (if (= :primitive-presence-decline (:reason (ex-data e))) nil (throw e))))))

(defn- checked-scalar-result [expression scalar-types]
  (some-> (checked-scalar-program expression scalar-types) (select-keys [:type])))

(defn checked-primitive-result
  "Prove primitive presence on normal return of one canonical scalar call using
   this same strict source-lowering authority. `present-types` contains ONLY
   independently proved-present lexical scalar values. No source code executes;
   this is neither purity nor nonthrowing evidence. The caller must retain the
   original initializer, its position, and its conversions/traps. Selected
   invk calls use checked-selected-primitive-result instead: known operands do
   not establish the selected implementation's result or definition freshness.
   The returned :type is the scalar grammar's dtype under the supplied inputs,
   NOT proof of an ordinary source call's physical result or boxed payload.
   Source presence consumers must use checked-scalar-normal-return instead."
  [expression present-types]
  (let [operation (descriptor/semantic-op expression)
        intrinsic (some-> operation intrinsics/canonical intrinsics/descriptor)
        arguments (vec (descriptor/call-args expression))
        known? (fn [argument]
                 (or (and (symbol? argument) (contains? present-types argument))
                     (and (number? argument) (inference/infer-arg-tag argument {}))))]
    (when (and (not (:dispatch? (descriptor/call-description expression)))
               (symbol? operation) (namespace operation) (descriptor/scalar-op? operation)
               intrinsic
               (every? known? arguments))
      (checked-scalar-result expression present-types))))

(defn checked-scalar-normal-return
  "Prove only nonnull-on-normal-return for a bounded closed numeric expression.
   Payload dtypes validate the existing scalar grammar; they are NOT actual
   argument carriers or source overload evidence. Consequently this API returns
   no dtype, payload or storage information. Unknown calls and lexical callees
   decline. The caller must keep the original producer, conversions and order."
  [expression present-types]
  (when (seq? expression)
    (let [closed?
          (loop [pending [[expression 0]] visits 0]
            (cond
              (empty? pending) true
              (>= visits 10000) false
              :else
              (let [[node depth] (peek pending)
                    remaining (pop pending)]
                (cond
                  (> depth 128) false
                  (number? node) (recur remaining (inc visits))
                  (symbol? node) (and (contains? present-types node)
                                      (recur remaining (inc visits)))
                  (seq? node)
                  (let [arguments (descriptor/call-args node)
                        argument-count (bounded-count (inc (- 10000 visits)) arguments)
                        operation (descriptor/semantic-op node)
                        cast (descriptor/cast-result-tag operation)]
                    (and (= operation (first node))
                         (not (contains? present-types operation))
                         (not (:raster.op/lexical-callee (meta node)))
                         (not= '.invk (first node))
                         (<= (+ visits (count remaining) argument-count) 10000)
                         (symbol? operation)
                         (contains? #{"clojure.core" "Math" "java.lang.Math"}
                                    (namespace operation))
                         (or (and cast (= 1 argument-count))
                             (and (or (descriptor/scalar-op? operation)
                                      (descriptor/comparison-kind operation))
                                  (some-> operation intrinsics/canonical intrinsics/descriptor)))
                         (recur (into remaining (map #(vector % (inc depth))
                                                     arguments))
                                (inc visits))))
                  :else false))))]
      (when (and closed? (checked-scalar-program expression present-types))
        {:presence :present}))))

(defn- strict-core-expression?
  "Closed scalar producer grammar, not a purity test. A root symbol may be
   nullable; only a real strict core call/cast proves a result on normal return."
  [expression params]
  (cond
    (number? expression) true
    (symbol? expression) (contains? params expression)
    (seq? expression)
    (let [operation (descriptor/semantic-op expression)
          arguments (descriptor/call-args expression)]
      (and (not= '.invk (first expression))
           (not (:lexical-callee (descriptor/call-description expression)))
           (symbol? operation)
           (contains? #{"clojure.core" "Math" "java.lang.Math"} (namespace operation))
           (or (and (descriptor/cast-result-tag operation) (= 1 (count arguments)))
               (and (or (descriptor/scalar-op? operation)
                        (descriptor/comparison-kind operation))
                    (some-> operation intrinsics/canonical intrinsics/descriptor)))
           (every? #(strict-core-expression? % params) arguments)))
    :else false))

(defn- qualify-source-casts
  "Resolve only existing bare cast spellings in the observed source namespace.
   A local or user Var named float must not borrow the core conversion contract."
  [body parameters body-context]
  (util/postwalk-preserving-meta
   (fn [node]
     (let [head (when (seq? node) (first node))]
       (if (and (symbol? head) (nil? (namespace head))
                (not (contains? parameters head)) (descriptor/cast-op? head))
         (let [operation (method-entry/observed-body-operation body-context head parameters)]
           (if (and operation (= "clojure.core" (namespace operation)))
             (util/remake-from node (cons operation (rest node)))
             node))
         node)))
   body))

(defn- selected-strict-scalar-source
  [expression]
  (let [{:keys [dispatch? semantic-op implementation-op arguments lexical-callee]}
        (descriptor/call-description expression)]
    (when (and dispatch? (not lexical-callee)
               (or (descriptor/scalar-op? semantic-op)
                   (descriptor/comparison-kind semantic-op))
               (some-> semantic-op intrinsics/canonical intrinsics/descriptor))
      ;; Discover only the candidate identity. Current metadata is not proof
      ;; that an existing implementation was emitted from that metadata.
      (when-let [candidate (method-entry/selected-definition
                            semantic-op implementation-op (count arguments))]
        (when-let [entry (method-entry/selected-source-entry-carriers
                         semantic-op implementation-op (count arguments) (:source-var candidate))]
          (let [{:keys [parameters] :as definition} (:definition entry)
                body-context (method-entry/selected-definition-body definition)
                source-body (:body body-context)
                body (when (= 1 (count source-body))
                       (qualify-source-casts (first source-body) (set parameters) body-context))]
            (when (and (seq? body) (strict-core-expression? body (set parameters)))
              {:definition definition :entry entry :body body :arguments arguments
               :operation semantic-op :implementation-op implementation-op})))))))

(defn checked-selected-primitive-result
  "Prove OUTPUT presence from the current selected implementation's closed
   strict scalar body. Inputs remain unknown/nullable. The exact receiver must
   match a live registered method, including its scalar signature and source.
   This never invokes a method, invents a registry, or authorizes moving/removing
   the original call. Requires an owning definition collector and its final
   guard. Current metadata must match the historical source entry consumed by
   the selected implementation. Missing/legacy lineage, generic calls and
   opaque/user helper bodies stay unknown; this query never forces a JIT."
  [expression]
  (method-entry/call-with-optional-definition-inputs
   (fn []
    (when-let [{:keys [definition body]} (selected-strict-scalar-source expression)]
    (let [{:keys [tags parameters return-tag]} definition
          scalar-types (mapv dtype/dtype-for-scalar-tag tags)
          result-type (dtype/dtype-for-scalar-tag return-tag)]
      (when (and (every? some? scalar-types) result-type)
        (let [proof (checked-scalar-result body (zipmap parameters scalar-types))]
          (when (= result-type (:type proof)) proof))))))))

(defn- completed-fp-body-carrier
  "Bounded completion summary INSIDE a selected primitive entry, not source inference.
   Only exact core binary FP operations and FP conversions are admitted. Reuse the
   emitter's arithmetic plan and the intrinsic table's independent totality facet."
  ([expression parameters] (completed-fp-body-carrier expression parameters false))
  ([expression parameters check-retained-types?]
   (let [actual
         (cond
           (symbol? expression) (get parameters expression)
           (instance? Double expression) Double/TYPE
           (instance? Float expression) Float/TYPE
           (seq? expression)
           (let [operation (descriptor/semantic-op expression)
                 arguments (vec (descriptor/call-args expression))
                 carriers (mapv #(completed-fp-body-carrier % parameters check-retained-types?) arguments)
                 intrinsic (intrinsics/descriptor operation)]
             (when (and (= operation (first expression))
                        (= "clojure.core" (namespace operation))
                        (not (contains? parameters operation))
                        (every? #{Float/TYPE Double/TYPE} carriers))
               (cond
                 (and (= 1 (count arguments)) (descriptor/cast-op? operation))
                 (let [target (types/tag->java-class (descriptor/cast-result-tag operation))
                       source (first carriers)]
                   ;; Do not borrow unchecked JVM narrowing for a checked source cast.
                   ;; Identity and Float->Double share the exact conversion contract.
                   (when (and (contains? #{Float/TYPE Double/TYPE} target)
                              (= [:exact :exact]
                                 (scalar-conversion/policy
                                  (if (= source Float/TYPE) :float :double)
                                  (if (= target Float/TYPE) :float :double))))
                     target))

                 ;; Nonthrowing evidence is independent of the result-carrier
                 ;; recipe. This summary owns only core comparisons and the
                 ;; existing binary arithmetic planner, not library functions.
                 (and (intrinsics/primitive-fp-total? operation carriers)
                      (or (= :cmp (:kind intrinsic))
                          (and (= :infix (:kind intrinsic))
                               (= 2 (:arity intrinsic))
                               (source-arithmetic/binary-operator? (:c intrinsic)))))
                 (if (= :cmp (:kind intrinsic))
                   Boolean/TYPE
                   (let [plan (source-arithmetic/binary-plan
                               (:c intrinsic)
                               (if (= Float/TYPE (first carriers)) :float :double)
                               (if (= Float/TYPE (second carriers)) :float :double))]
                     (when (= :primitive (:kind plan))
                       (case (:result-carrier plan) :float Float/TYPE :double Double/TYPE nil)))))))
           :else nil)
         tag (or (:raster.type/tag (meta expression)) (:tag (meta expression)))
         retained (or (when (and (keyword? tag) (dtype/known? tag)) (dtype/canon tag))
                      (dtype/dtype-for-scalar-tag tag))
         actual-type (when actual
                       (if (= Boolean/TYPE actual) :predicate
                           (dtype/dtype-for-scalar-tag (symbol (.getName ^Class actual)))))]
     ;; The ordinary summary does not lower a replacement. A payload recipe
     ;; does: every retained width used by the SSA lowerer must independently
     ;; agree with the actual primitive operand plan, including nested nodes.
     (when (and actual (or (not check-retained-types?) (nil? retained)
                          (= retained actual-type)))
       actual))))

(defn- completed-fp-argument?
  "A logical dtype or nullable reference class cannot discharge entry unboxing."
  [{:keys [carrier presence builtin-class]} target]
  (and (= :present presence)
       (or (and (contains? #{Float/TYPE Double/TYPE} carrier)
                (or (= target Double/TYPE) (= carrier Float/TYPE)))
           (and (class? carrier) (not (.isPrimitive ^Class carrier))
                (contains? #{Float Double} builtin-class)
                (or (= target Double/TYPE) (= builtin-class Float))
                (.isAssignableFrom ^Class carrier ^Class builtin-class)))))

(defn checked-core-fp-evaluation
  "Summarize one original core arithmetic/comparison call AFTER its operands complete.
   Reuses the selected-body carrier planner and totality check, not inferred tags.
   One actual primitive Double operand fixes the source's Double computation.
   The other may be primitive FP or a proved present builtin FP payload behind
   its actual reference carrier. Input carrier facts are never upgraded. Calls
   without that Double anchor, integral arithmetic, casts and lexical calls abstain.
   This grants neither operand completion nor permission to move/remove the call."
  [expression argument-facts source-ns]
  (method-entry/call-with-optional-definition-inputs
   (fn []
     (let [{:keys [semantic-op arguments lexical-callee]} (descriptor/call-description expression)
           intrinsic (intrinsics/descriptor semantic-op)
           carriers (mapv :carrier argument-facts)]
       (when (and method-entry/*emission-inputs* (instance? clojure.lang.Namespace source-ns)
                  (seq? expression) (vector? argument-facts)
                  (= semantic-op (first expression)) (not lexical-callee)
                  (symbol? semantic-op) (= "clojure.core" (namespace semantic-op))
                  (= 2 (count arguments) (count argument-facts))
                  (some #{Double/TYPE} carriers)
                  (every? #(completed-fp-argument? % Double/TYPE) argument-facts)
                  (or (= :cmp (:kind intrinsic))
                      (and (= :infix (:kind intrinsic))
                           (source-arithmetic/binary-operator? (:c intrinsic)))))
         (when (intrinsic-source/observe-original! source-ns semantic-op)
           (let [parameters '[core-left core-right]
                 body (apply list semantic-op parameters)
                 source-carriers (mapv #(if (.isPrimitive ^Class %)
                                          (keyword (.getName ^Class %)) :ref) carriers)
                 source-result (if (= :cmp (:kind intrinsic)) Boolean/TYPE
                                   (case (:result-carrier
                                          (apply source-arithmetic/binary-plan
                                                 (:c intrinsic) source-carriers))
                                     :double Double/TYPE nil))
                 ;; The original source overload still sees reference ports.
                 ;; Present Float/Double payloads make its Double conversion exact;
                 ;; only the arithmetic proof uses the resulting numeric carriers.
                 arithmetic-carriers (mapv #(if (.isPrimitive ^Class %) % Double/TYPE) carriers)
                 actual (completed-fp-body-carrier body (zipmap parameters arithmetic-carriers))]
             (when (and source-result (= source-result actual))
               {:result-carrier actual :scope :completed-fp-scalar :presence :present
                :builtin-class (get types/primitive-info (symbol (.getName ^Class actual)))
                :nonthrowing? true}))))))))

(defn checked-selected-primitive-evaluation
  "Prove a bounded selected scalar call has no source arithmetic/conversion failure.
   Argument facts describe independently proved, ALREADY completed operands in call
   order: actual :carrier Class, :presence, and optional present :builtin-class.
   They are owner-private evidence, not consumer dtype annotations. Argument evaluation
   itself is never discharged. Requires the existing definition owner/final guard.

   The method's actual primitive entry, original source lineage, strict scalar body,
   result dtype, and FP completion must all agree. Object returns remain Object;
   builtin numeric result presence is distinct. Unknown/nullable/generic/integral
   calls abstain, as do narrowing argument conversions. This query neither
   executes code nor grants external purity. Its :completed-fp-scalar scope is
   arithmetic/conversion completion only: it is not proof against cold JIT or
   VM allocation failure and must never feed global removability directly."
  [expression argument-facts]
  (method-entry/call-with-optional-definition-inputs
   (fn []
    (when-let [{:keys [definition entry body arguments]}
             (selected-strict-scalar-source expression)]
    (let [{:keys [parameters tags return-tag]} definition
          carriers (:parameter-carriers entry)]
      (when (and entry (vector? argument-facts)
                 (= (count arguments) (count argument-facts))
                 (every? #{Float/TYPE Double/TYPE} carriers)
                 (every? true? (map completed-fp-argument? argument-facts carriers)))
        (let [actual (completed-fp-body-carrier body (zipmap parameters carriers))
              result-type (if (= return-tag 'boolean) :predicate
                              (dtype/dtype-for-scalar-tag return-tag))
              proof (when actual
                      (checked-scalar-result body
                                             (zipmap parameters (map dtype/dtype-for-scalar-tag tags))))
              expected (when result-type
                         (if (= :predicate result-type) Boolean/TYPE
                             (types/tag->java-class (dtype/scalar-tag-for-dtype result-type))))]
          (when (and actual (= actual expected) (= result-type (:type proof)))
            {:type result-type :result-carrier (:result-carrier entry)
             :scope :completed-fp-scalar
             :presence :present :builtin-class (case result-type
                                                :float Float :double Double :predicate Boolean)
             :nonthrowing? true}))))))))

(defn checked-selected-fp-payload
  "Retain a primitive SSA computation behind an ACTUAL owned Object-return bridge.
   This bounded leaf admits only primitive FP formals and the same closed core
   body checked by completed-fp evaluation. No query invokes the JIT or a method.
   Cold source entries and unknown Object/generic/nested selected recipes abstain.

   Physical result remains Object. Payload type is NOT the carrier supplied to a
   parent's overload selection. A consumer still owes original argument evaluation
   and conversion, use-closed box-storage erasure, and the owning definition guard.
   This does not authorize arbitrary source inlining, motion or reassociation."
  [expression argument-facts]
  (method-entry/call-with-optional-definition-inputs
   (fn []
     (when-let [{:keys [entry body arguments definition]}
                (selected-strict-scalar-source expression)]
       (when-let [bridge (and (not (:pending-source? entry))
                             ((requiring-resolve 'raster.compiler.backend.jvm.bytecode/retained-typed-return-bridge)
                              (:emission entry)))]
         (let [parameters (:parameters definition)
               carriers (:parameter-carriers entry)
               actual (completed-fp-body-carrier body (zipmap parameters carriers) true)
               program (when (and (vector? argument-facts)
                                  (= (count arguments) (count argument-facts))
                                  (= (:invocation-method entry) (:invocation-method bridge))
                                  (= carriers (:parameter-carriers bridge))
                                  (every? true? (map completed-fp-argument? argument-facts carriers))
                                  (= actual (:payload-carrier bridge)))
                         (checked-scalar-program
                          body (zipmap parameters (map #(if (= Float/TYPE %) :float :double) carriers))))]
           (when (= (if (= actual Float/TYPE) :float :double) (:type program))
             {:scope :owned-fp-return-payload :result-carrier Object :payload-carrier actual
              :parameters parameters :parameter-carriers carriers :arguments (vec arguments)
              :computation program :bridge bridge})))))))

(defn canonical-selected-fp-operation
  "Callee-only correspondence for a selected primitive FP arithmetic leaf.

   The actual original body must be the same canonical core operation over its
   ordered formals. Only identity result casts may surround it. This is NOT
   operand completion, generic-call purity, Object erasure or permission to move
   the source call. A wider body needs its actual owned computation recipe.
   Existing source-entry and bootstrap definition guards own all assumptions."
  [expression]
  (method-entry/call-with-optional-definition-inputs
   (fn []
     (when-let [{:keys [entry body definition operation]}
                (selected-strict-scalar-source expression)]
       (let [parameters (:parameters definition)
             carriers (:parameter-carriers entry)
             intrinsic (intrinsics/descriptor operation)
             scope (zipmap parameters carriers)
             actual (completed-fp-body-carrier body scope true)
             expected (some-> (:return-tag definition) types/tag->java-class)
             ;; Do not erase Float checkpoints or even an exact widening:
             ;; the computation width must stay the source operation's width.
             primitive-body
             (loop [source body]
               (let [op (when (seq? source) (descriptor/semantic-op source))
                     arguments (vec (descriptor/call-args source))
                     operand (first arguments)]
                 (if (and (seq? source) (= op (first source)) (= 1 (count arguments))
                          (descriptor/cast-op? op)
                          (= (completed-fp-body-carrier source scope true)
                             (completed-fp-body-carrier operand scope true))
                          (some? (completed-fp-body-carrier operand scope true)))
                   (do
                     (intrinsic-source/observe-original! (the-ns 'clojure.core) op)
                     (recur operand))
                   source)))
             core-op (when (seq? primitive-body) (first primitive-body))]
         (when (and (= :infix (:kind intrinsic))
                    (source-arithmetic/binary-operator? (:c intrinsic))
                    (= 2 (count parameters) (count carriers))
                    (every? #{Float/TYPE Double/TYPE} carriers)
                    (contains? #{Float/TYPE Double/TYPE} actual)
                    (= expected actual)
                    (symbol? core-op) (= "clojure.core" (namespace core-op))
                    (= parameters (vec (rest primitive-body)))
                    (= (intrinsics/canonical operation) (intrinsics/canonical core-op)))
           (intrinsic-source/observe-original! (the-ns 'clojure.core) core-op)
           {:scope :canonical-selected-fp-operation
            :operation (intrinsics/canonical operation)
            :parameter-carriers carriers :result-carrier (:result-carrier entry)
            :payload-carrier actual}))))))

(defn ^:no-doc check-reduction-fp-correspondence
  "Conditional FP value/checkpoint correspondence at an owning reduction constructor.

   `original` must be the owner's source occurrence; `product` is its actual
   constructed ProductReduction. Storage and primitive scalar facts are supplied
   by that owner, never inferred from desired result tags. Only one FP carry,
   direct index reads, sequential let* and authenticated core FP arithmetic are covered.
   Selected calls abstain: a boxed payload is not its parent's operand carrier.
   This query does not establish source ownership, a physical JVM result carrier,
   operand/count completion, bounds, purity or permission to reorder a reduction.
   The returned source-count obligation retains the original checked Int conversion;
   it is not evidence that a symbolic bound or its conversion completes.
   Unknown correspondence abstains; definition-ownership failures still propagate."
  [original product {:keys [source-ns array-types scalar-facts]}]
  (method-entry/call-with-optional-definition-inputs
   (fn []
     (when (and method-entry/*emission-inputs*
                (instance? clojure.lang.Namespace source-ns)
                (seq? original) (= 6 (bounded-count 7 original))
                (= 'raster.par/reduce (first original)))
       (reduction/validate! product)
       (let [abstain! (fn [& _]
                        (throw (ex-info "Outside conditional FP reduction correspondence"
                                        {:reason ::reduction-correspondence-decline})))
             fp? #{:float :double}
             tag-of (fn [x]
                      (let [tag (or (:raster.type/tag (meta x)) (:tag (meta x)))]
                        (or (when (and (keyword? tag) (dtype/known? tag)) (dtype/canon tag))
                            (dtype/dtype-for-scalar-tag tag))))
             typed (fn [x type]
                     (when-let [retained (tag-of x)]
                       (when-not (= retained type) (abstain!)))
                     (if (instance? clojure.lang.IObj x)
                       (with-meta x (assoc (meta x) :raster.type/tag
                                          (dtype/scalar-tag-for-dtype type))) x))]
         (try
           ;; Bound analysis cost and recursion before either the correspondence
           ;; traversal or the existing scalar lowerer visits an expression.
           (loop [pending [[original 0] [(:results (:step product)) 0]] visits 0]
             (when-let [[node depth] (peek pending)]
               (when (or (>= visits 10000) (> depth 128)) (abstain!))
               (let [remaining (pop pending)
                     capacity (- 10000 visits (count remaining))]
                 ;; Bound child realization BEFORE growing the work stack; a
                 ;; wide or lazy collection must not evade the visit budget.
                 (when (and (coll? node)
                            (> (bounded-count (inc capacity) node) capacity)) (abstain!))
                 (recur (if (coll? node)
                          (into remaining (map #(vector % (inc depth)) node))
                          remaining)
                        (inc visits)))))
           (let [{:keys [acc init idx bound body]} (par/extract-par-reduce-info original)
                 component (first (:components product))
                 region (reduction/fold-region product)
                 target (:dtype component)
                 scalar-types (into {}
                                    (keep (fn [[id {:keys [carrier presence]}]]
                                            (when (and (= :present presence)
                                                       (contains? #{Float/TYPE Double/TYPE} carrier))
                                              [id (if (= carrier Float/TYPE) :float :double)])))
                                    scalar-facts)]
             (when-not (and (= 1 (count (:components product))) (fp? target)
                            (= acc (:accumulator component)) (= idx (:index product))
                            (symbol? acc) (symbol? idx) (not= acc idx) (empty? (:bindings region))
                            (= 1 (count (:results region)))
                            ;; Initializers are retained by the actual constructor. Equal
                            ;; numeric values must not substitute a different source width.
                            (identical? init (:neutral component))
                            (or (symbol? bound)
                                (and (integer? bound) (<= Integer/MIN_VALUE bound Integer/MAX_VALUE))))
               (abstain!))
             (letfn [(check [expression env]
                       (let [[type normalized]
                             (cond
                               (instance? Float expression) [:float expression]
                               (instance? Double expression) [:double expression]
                               (symbol? expression)
                               (when-let [type (get env expression)] [type expression])

                               (and (seq? expression) (= 'let* (first expression)))
                               (let [[_ bindings & bodies] expression]
                                 (when-not (and (vector? bindings) (even? (count bindings))
                                                (= 1 (count bodies))) (abstain!))
                                 (let [[scope bindings]
                                       (reduce (fn [[scope out] [id value]]
                                                 (when-not (and (symbol? id) (not= idx id)) (abstain!))
                                                 (let [[type value] (check value scope)]
                                                   [(assoc scope id type)
                                                    (conj out (typed id type) value)]))
                                               [env []] (partition 2 bindings))
                                       [type body] (check (first bodies) scope)]
                                   [type (with-meta (list 'let* bindings body) (meta expression))]))

                               (seq? expression)
                               (let [{:keys [semantic-op arguments lexical-callee implementation-op]}
                                     (descriptor/call-description expression)
                                     core? (and (= semantic-op (first expression))
                                                (= "clojure.core" (namespace semantic-op)))]
                                 (when (or lexical-callee (contains? env implementation-op)) (abstain!))
                                 (cond
                                   (and core? (= 'clojure.core/aget semantic-op)
                                        (= 2 (count arguments)) (= idx (second arguments))
                                        (symbol? (first arguments))
                                        (not (contains? env (first arguments))))
                                   (let [type (get array-types (first arguments))]
                                     (when-not (fp? type) (abstain!))
                                     (intrinsic-source/observe-original! source-ns semantic-op)
                                     [type expression])

                                   (and core? (descriptor/cast-op? semantic-op)
                                        (= 1 (count arguments)))
                                   (let [[source operand] (check (first arguments) env)
                                         target (dtype/dtype-for-scalar-tag
                                                 (descriptor/cast-result-tag semantic-op))]
                                     (when-not (fp? target) (abstain!))
                                     (intrinsic-source/observe-original! source-ns semantic-op)
                                     (when-not (or (= source target) (= target :double)
                                                   (numeric-constant/source-value expression))
                                       (abstain!))
                                     [target (with-meta (list semantic-op operand) (meta expression))])

                                   :else
                                   (let [_ (when-not core? (abstain!))
                                         intrinsic (intrinsics/descriptor semantic-op)
                                         checked (mapv #(check % env) arguments)
                                         types (mapv first checked)]
                                     (when-not (and (= 2 (count checked)) (= :infix (:kind intrinsic))
                                                    (source-arithmetic/binary-operator? (:c intrinsic))
                                                    (every? fp? types))
                                       (abstain!))
                                     (intrinsic-source/observe-original! source-ns semantic-op)
                                     (let [plan (apply source-arithmetic/binary-plan (:c intrinsic) types)
                                           type (:result-carrier plan)
                                           op (symbol "clojure.core" (:c intrinsic))]
                                       (when-not (= :primitive (:kind plan)) (abstain!))
                                       [type (with-meta (apply list op (map second checked))
                                                       (meta expression))]))))
                               :else nil)]
                         (when-not (fp? type) (abstain!))
                         [type (typed normalized type)]))]
               (let [[initial-type _] (check init scalar-types)
                     env (assoc (dissoc scalar-types idx) acc target)
                     [update-type source-step] (check body env)
                     plan (source-arithmetic/loop-initializer-plan acc init initial-type update-type)
                     [_ actual-step] (check (first (:results region)) env)]
                 (when-not (and (= target update-type (:slot-carrier plan))
                                (= source-step actual-step)) (abstain!))
                 (let [options {:array-types array-types :arrays (set (keys array-types))
                                :scalar-types env :index-scope #{idx}
                                :source-region [source-step actual-step] :require-source-types? true
                                :id-prefix "fp-correspondence" :decline! abstain!
                                :lower-index (fn [coordinate _]
                                               (if (= coordinate idx) idx (abstain!)))}
                       lower (fn [expression]
                               ((:lower (make-lowerer options)) expression target env))]
                   (when-not (= (lower source-step) (lower actual-step)) (abstain!))
                   {:scope :conditional-fp-reduction-correspondence :dtype target
                    :checkpoints-preserved? true :zero-trip :initializer
                    :source-count-obligation {:conversion :checked-int :evaluation :original-position}}))))
           (catch clojure.lang.ExceptionInfo error
             (when-not (= ::reduction-correspondence-decline (:reason (ex-data error)))
               (throw error)))))))))
